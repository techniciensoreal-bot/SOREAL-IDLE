export function idleBossVarianteDifficulteV1(difficulte){
  const d=String(difficulte||"").trim().toLowerCase();
  return d==="difficile"?"evil":d==="extreme"?"sadistic":"normal";
}
export function idleBossCleR2V1(id,difficulte){
  const n=Math.floor(Number(id)||0);
  const variante=idleBossVarianteDifficulteV1(difficulte);
  if(variante!=="normal"){
    const t=variante==="evil"?IDLE_BOSS_FICHIERS_EVIL_R2_V1:IDLE_BOSS_FICHIERS_SADISTIC_R2_V1;
    const f=t[n];
    if(f)return "idle/"+(variante==="evil"?"bosses-evil":"bosses-sadistic")+"/Boss_"+String(n).padStart(3,"0")+"_"+f;
    return "";
  }
  const f=IDLE_BOSS_FICHIERS_R2_V1[n];
  return f?"idle/bosses/Boss_"+String(n).padStart(3,"0")+"_"+f:"";
}
